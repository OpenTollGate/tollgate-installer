// pkgverify_test.go pins the package-integrity contract added for the
// pre-release security audit finding C2-I-03 ("no checksum or signature
// verification in the entire install path").
//
// The behaviour under test, in the words of the finding: the installer used to
// accept arbitrary bytes and install them as root (`opkg --force-downgrade …`,
// `apk add --allow-untrusted …`), so a corrupted, truncated or substituted
// package produced a GREEN "done" step. These tests drive the real verifier and
// assert that (a) bytes matching the published digest pass, (b) bytes that do
// not match FAIL, naming the asset and both digests, (c) a package that cannot
// be the expected format FAILS, and (d) a release that publishes no digest is
// reported as UNVERIFIED — never as a pass.

// fakeIPK / fakeAPK are structurally plausible package blobs (correct magic,
// above the size floor) used as stand-ins for the ~8 MB release assets.
func fakeIPK(n int) []byte {
	b := make([]byte, n)
	copy(b, []byte{0x1f, 0x8b, 0x08, 0x00})
	for i := 4; i < n; i++ {
		b[i] = byte(i * 7)
	}
	return b
}

func fakeAPK(n int) []byte {
	b := make([]byte, n)
	copy(b, []byte(apkMagic))
	for i := 4; i < n; i++ {
		b[i] = byte(i*13 + 5)
	}
	return b
}

func digestOf(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

